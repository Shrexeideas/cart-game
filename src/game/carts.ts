export function getCartDefinition(id: CartId): CartDefinition {
  return CART_CATALOG.find((c) => c.id === id) ?? CART_CATALOG[0];
}

export function applyCartModifiersToHandling(
  base: CartHandlingProfile,
  cart: CartDefinition,
  chaosMode: boolean
): CartHandlingProfile {
  const m = cart.physics;
  const chaosMult = chaosMode ? 1.22 : 1.0;
  return {
    maxSpeed: base.maxSpeed * m.maxSpeedMult * (chaosMode ? 1.12 : 1.0),
    pushForce: base.pushForce * m.pushMult,
    reverseForce: base.reverseForce * m.reverseMult,
    steerTorque: base.steerTorque * m.steerMult,
    casterLagRate: Math.max(1.8, base.casterLagRate * m.casterLagMult),
    badWheelPull: base.badWheelPull + m.badWheelBias,
    wobbleAmplitude: Math.max(0.03, (base.wobbleAmplitude + m.wobbleBias) * chaosMult),
    reverseInstability: Math.max(
      0.15,
      base.reverseInstability * m.reverseInstabilityMult * chaosMult
    ),
    lateralGrip: Math.max(1.6, base.lateralGrip * m.lateralGripMult),
    slopeX: base.slopeX + (chaosMode ? 0.25 : 0),
    slopeZ: base.slopeZ - (chaosMode ? 0.25 : 0),
  };
}
